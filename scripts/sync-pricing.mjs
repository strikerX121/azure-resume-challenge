// Pricing sync: /shop prices come from the ARC pricing playbook, not from
// numbers typed into shop.astro.
//
// Source of truth: arc-client-os/references/pricing-and-playbook.md (the ARC
// Client OS Hermes skill). That file lives on Antonio's machine, not in this
// repo, and the GitHub Actions build cannot read it. So the pipeline is:
//
//   1. `npm run build` runs this script first (prebuild).
//   2. If the playbook is reachable (local build), it is parsed and
//      src/data/pricing.snapshot.json is rewritten from it, with the source's
//      sha256 recorded.
//   3. If it is not reachable (CI), the committed snapshot is used as-is.
//   4. `--check` (part of npm run verify) fails when the playbook is reachable
//      and its hash no longer matches the snapshot, i.e. someone changed a
//      price and did not rebuild before committing.
//
// What is parsed, and nothing else:
//   - Antonio's hourly rate:   "use TTD $400 for calculations"
//   - the USD/TTD conversion:  "Convert at 7.5"
//   - OPTIONAL fixed package prices, if the playbook ever gains a section like
//
//       ## Website Packages
//       | Package | Price |
//       |---|---|
//       | Discovery Call | USD 150 |
//
//     A package listed there uses that exact figure. A package not listed there
//     is derived from the hourly rate and its duration (see
//     src/data/shop-packages.ts), or shown as quote-only if it has no duration.
//
// A playbook that is present but cannot be parsed is a HARD failure. Guessing
// a price is worse than not building.
//
// Usage:
//   node scripts/sync-pricing.mjs           sync (or keep snapshot if no source)
//   node scripts/sync-pricing.mjs --check   fail if the snapshot is stale
//   ARC_PRICING_PLAYBOOK=/path/to/file.md node scripts/sync-pricing.mjs

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const SNAPSHOT = path.join('src', 'data', 'pricing.snapshot.json');

function defaultSource() {
  const base = process.env.LOCALAPPDATA;
  if (!base) return null;
  return path.join(
    base, 'hermes', 'profiles', 'client-apps', 'skills', 'productivity',
    'arc-client-os', 'references', 'pricing-and-playbook.md'
  );
}

const SOURCE = process.env.ARC_PRICING_PLAYBOOK || defaultSource();
const CHECK = process.argv.includes('--check');

function sha256(text) {
  return crypto.createHash('sha256').update(text.replace(/\r\n/g, '\n')).digest('hex');
}

function parsePlaybook(md) {
  const text = md.replace(/\r\n/g, '\n');
  const rate = text.match(/use\s+TTD\s+\$?([\d,]+)\s+for\s+calculations/i);
  const fx = text.match(/Convert\s+at\s+([\d.]+)/i);
  if (!rate) throw new Error('could not find "use TTD $N for calculations" (hourly rate)');
  if (!fx) throw new Error('could not find "Convert at N" (USD to TTD rate)');

  const packages = {};
  const section = text.match(/^##\s+Website Packages\s*\n([\s\S]*?)(?=^##\s|(?![\s\S]))/im);
  if (section) {
    for (const line of section[1].split('\n')) {
      const m = line.match(/^\|\s*([^|]+?)\s*\|\s*(USD|TTD)\s*\$?([\d,]+)\s*\|/i);
      if (m && !/^package$/i.test(m[1]) && !/^-+$/.test(m[1])) {
        packages[m[1].trim()] = { currency: m[2].toUpperCase(), amount: Number(m[3].replace(/,/g, '')) };
      }
    }
  }

  return {
    antonioRateTTDPerHour: Number(rate[1].replace(/,/g, '')),
    usdToTtd: Number(fx[1]),
    packages,
  };
}

function readSnapshot() {
  if (!fs.existsSync(SNAPSHOT)) return null;
  return JSON.parse(fs.readFileSync(SNAPSHOT, 'utf8'));
}

const sourceExists = SOURCE && fs.existsSync(SOURCE);

if (!sourceExists) {
  const snap = readSnapshot();
  if (!snap) {
    console.error(`sync-pricing: no playbook at ${SOURCE ?? '(LOCALAPPDATA unset)'} and no committed snapshot. Cannot price /shop.`);
    process.exit(1);
  }
  console.log(`sync-pricing: playbook not reachable here (expected in CI). Using committed snapshot from ${snap.syncedAt}, source sha256 ${snap.sourceSha256.slice(0, 12)}.`);
  process.exit(0);
}

const md = fs.readFileSync(SOURCE, 'utf8');
const hash = sha256(md);

let parsed;
try {
  parsed = parsePlaybook(md);
} catch (e) {
  console.error(`sync-pricing: playbook at ${SOURCE} is present but unparseable: ${e.message}`);
  process.exit(1);
}

if (CHECK) {
  const snap = readSnapshot();
  if (!snap || snap.sourceSha256 !== hash) {
    console.error('sync-pricing --check: src/data/pricing.snapshot.json is stale relative to the playbook. Run `npm run sync:pricing` and commit the result.');
    process.exit(1);
  }
  console.log('sync-pricing --check: snapshot matches the playbook.');
  process.exit(0);
}

const prev = readSnapshot();
if (prev && prev.sourceSha256 === hash) {
  console.log('sync-pricing: snapshot already matches the playbook, unchanged.');
  process.exit(0);
}

const snapshot = {
  _comment: 'Generated by scripts/sync-pricing.mjs from arc-client-os/references/pricing-and-playbook.md. Do not edit by hand.',
  source: 'arc-client-os/references/pricing-and-playbook.md',
  sourceSha256: hash,
  syncedAt: new Date().toISOString(),
  ...parsed,
};
fs.writeFileSync(SNAPSHOT, JSON.stringify(snapshot, null, 2) + '\n');
console.log(`sync-pricing: wrote ${SNAPSHOT} (rate TTD ${parsed.antonioRateTTDPerHour}/hr, fx ${parsed.usdToTtd}, ${Object.keys(parsed.packages).length} fixed package price(s)).`);
